"""Read and validate generated ML result artifacts without loading models."""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

from backend.models.ml_results import (
    ArtifactNotFoundError,
    ArtifactReadError,
    ArtifactSchemaError,
    ArtifactSpec,
)


PROJECT_ROOT = Path(__file__).resolve().parents[2]
PROCESSED_DATA_DIR = PROJECT_ROOT / "processed_data"
ML_MODELS_DIR = PROJECT_ROOT / "ml_models"

RISK_PREDICTIONS = ArtifactSpec(
    "risk_predictions.csv",
    frozenset(
        {
            "BENE_ID",
            "high_utilization_pattern",
            "predicted_high_utilization_pattern",
            "high_utilization_probability",
            "dataset_split",
        }
    ),
)
ANOMALY_RESULTS = ArtifactSpec(
    "anomaly_results.csv",
    frozenset(
        {
            "BENE_ID",
            "anomaly_score",
            "anomaly_flag",
            "anomaly_rank",
            "model_version",
            "generated_at",
        }
    ),
)
OVERLAP_RESULTS = ArtifactSpec(
    "xgboost_isolation_forest_overlap.csv",
    frozenset(
        {
            "BENE_ID",
            "anomaly_score",
            "anomaly_flag",
            "high_utilization_pattern",
            "comparison_group",
        }
    ),
)
ANOMALY_SUMMARY_FIELDS = frozenset(
    {"model_purpose", "total_members", "number_of_anomalies", "anomaly_percentage", "limitation"}
)


def _artifact_path(directory: Path, filename: str) -> Path:
    """Resolve a known artifact name without exposing its path to clients."""
    path = directory / filename
    if not path.is_file():
        raise ArtifactNotFoundError("A required ML results artifact is not available.")
    return path


def _parse_value(column: str, value: str | None) -> Any:
    """Convert known numeric result columns while preserving member identifiers."""
    if value is None or value == "":
        return None
    if column in {"high_utilization_pattern", "predicted_high_utilization_pattern", "anomaly_flag", "anomaly_rank"}:
        try:
            return int(value)
        except ValueError as error:
            raise ArtifactReadError("An ML results CSV contains an invalid numeric value.") from error
    if column in {"high_utilization_probability", "anomaly_score"}:
        try:
            return float(value)
        except ValueError as error:
            raise ArtifactReadError("An ML results CSV contains an invalid numeric value.") from error
    return value


def _read_csv(spec: ArtifactSpec) -> list[dict[str, Any]]:
    path = _artifact_path(PROCESSED_DATA_DIR, spec.filename)
    try:
        with path.open("r", encoding="utf-8-sig", newline="") as file:
            reader = csv.DictReader(file)
            fieldnames = set(reader.fieldnames or [])
            if not spec.required_fields.issubset(fieldnames):
                raise ArtifactSchemaError("An ML results artifact has an unexpected schema.")
            return [
                {column: _parse_value(column, value) for column, value in row.items()}
                for row in reader
            ]
    except ArtifactSchemaError:
        raise
    except (OSError, UnicodeDecodeError, csv.Error) as error:
        raise ArtifactReadError("An ML results CSV could not be read.") from error


def _read_json(directory: Path, filename: str, required_fields: frozenset[str]) -> dict[str, Any]:
    path = _artifact_path(directory, filename)
    try:
        with path.open("r", encoding="utf-8") as file:
            data = json.load(file)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ArtifactReadError("An ML results JSON artifact could not be read.") from error
    if not isinstance(data, dict) or not required_fields.issubset(data):
        raise ArtifactSchemaError("An ML results artifact has an unexpected schema.")
    return data


def read_risk_predictions() -> list[dict[str, Any]]:
    """Return historical high-utilization pattern prediction records."""
    return _read_csv(RISK_PREDICTIONS)


def read_anomalies() -> list[dict[str, Any]]:
    """Return utilization anomaly records; anomaly score is not a clinical risk probability."""
    return _read_csv(ANOMALY_RESULTS)


def read_anomaly_summary() -> dict[str, Any]:
    """Return the generated utilization-anomaly summary without alteration."""
    return _read_json(PROCESSED_DATA_DIR, "anomaly_summary.json", ANOMALY_SUMMARY_FIELDS)


def read_overlap() -> list[dict[str, Any]]:
    """Return analytical overlap of historical high utilization and utilization anomalies."""
    return _read_csv(OVERLAP_RESULTS)


def read_model_metadata() -> dict[str, Any]:
    """Return only metrics and metadata already generated by the offline ML workflows."""
    xgboost_baseline = _read_json(
        ML_MODELS_DIR,
        "xgboost_metrics.json",
        frozenset({"model_name", "model_purpose", "target_definition", "test_metrics"}),
    )
    xgboost_tuned = _read_json(
        ML_MODELS_DIR,
        "xgboost_metrics_tuned.json",
        frozenset({"model_purpose", "selected_experiment", "selected_threshold", "tuned_xgboost"}),
    )
    isolation_metrics = _read_json(
        ML_MODELS_DIR,
        "isolation_forest_metrics.json",
        frozenset({"model_purpose", "selected_configuration", "limitation"}),
    )
    isolation_metadata = _read_json(
        ML_MODELS_DIR,
        "isolation_forest_feature_metadata.json",
        frozenset({"model_version", "model_type", "selected_configuration", "score_interpretation"}),
    )
    return {
        "xgboost": {"baseline_metrics": xgboost_baseline, "tuned_metrics": xgboost_tuned},
        "isolation_forest": {"metrics": isolation_metrics, "feature_metadata": isolation_metadata},
        "limitations": {
            "xgboost": "Historical utilization-pattern prioritization for proactive care navigation; not an emergency-necessity determination.",
            "isolation_forest": (
                "Isolation Forest detects unusual utilization patterns within the observed data. "
                "An anomaly is not evidence of medical necessity, clinical deterioration, "
                "inappropriate ED use, or ED avoidability."
            ),
        },
    }
